class DSU:
 def __init__(self):self.p={}
 def root(self,x):
  self.p.setdefault(x,x)
  while self.p[x]!=x:self.p[x]=self.p[self.p[x]];x=self.p[x]
  return x
 def join(self,a,b):
  a=self.root(a);b=self.root(b)
  if a!=b:self.p[max(a,b)]=min(a,b)
