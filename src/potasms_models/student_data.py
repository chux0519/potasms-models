def digest(p):
 h=hashlib.sha256()
 with Path(p).open('rb') as f:
  for b in iter(lambda:f.read(1024*1024),b''):h.update(b)
 return h.hexdigest()
def key(s):return re.sub(r'\s+',' ',unicodedata.normalize('NFKC',s).casefold()).strip()
